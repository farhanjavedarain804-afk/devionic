/**
 * Add border to all pages of a multi-page document
 */
export const addBorderToAllPages = (doc: jsPDF) => {
  const totalPages = doc.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    addPageBorder(doc);
  }
};

