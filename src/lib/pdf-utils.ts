// Safe Date Formatting
export const formatDateSafe = (date: any, formatStr: string = "dd/MM/yyyy") => {
  try {
    if (!date) return "N/A";
    const d = new Date(date);
    if (!isValid(d)) return "N/A";
    return format(d, formatStr);
  } catch {
    return "N/A";
  }
};

// Safe Items Parsing
export const parseItems = (items: any): any[] => {
  if (!items) return [];
  if (Array.isArray(items)) return items;
  if (typeof items === "string") {
    try {
      const parsed = JSON.parse(items);
      return Array.isArray(parsed) ? parsed : [];
    } catch {
      return [];
    }
  }
  return [];
};

// Generate document number in format: DEV-DDMMYYYY-TYPE-XXXX
export const generateDocNumber = (seq: number = 1, type: DocType = "HO"): string => {
  const now = new Date();
  const dateStr = `${String(now.getDate()).padStart(2, "0")}${String(now.getMonth() + 1).padStart(2, "0")}${now.getFullYear()}`;
  return `DEV-${dateStr}-${type}-${String(seq).padStart(4, "0")}`;
};

// Draw a barcode-like pattern (black bars on white)
const drawBarcode = (doc: jsPDF, text: string, x: number, y: number, width: number, height: number) => {
  const hash = text.split("").reduce((a, c) => a + c.charCodeAt(0), 0);
  let currentX = x;
  const numBars = Math.floor(width / 1.5);

  for (let i = 0; i < numBars; i++) {
    const isThick = ((hash * (i + 1)) % 3) !== 0;
    const w = isThick ? 1.0 : 0.5;
    const show = ((hash * (i + 1)) % 5) !== 0;
    if (show) {
      doc.setFillColor(0, 0, 0);
      doc.rect(currentX, y, w, height, "F");
    }
    currentX += 1.5;
  }

  doc.setFontSize(7);
  doc.setTextColor(0, 0, 0);
  doc.text(String(text), x + width / 2, y + height + 4, { align: "center" });
};

// Load icon logo as base64
let iconLogoCache: string | null = null;

const loadIconLogo = async (): Promise<string | null> => {
  if (iconLogoCache) return iconLogoCache;
  try {
    const logoModule = await import("@/assets/devionic-icon.png");
    const logoUrl = logoModule.default || logoModule;
    return new Promise((resolve) => {
      const img = new Image();
      img.crossOrigin = "anonymous";
      img.onload = () => {
        try {
          const canvas = document.createElement("canvas");
          canvas.width = img.width;
          canvas.height = img.height;
          const ctx = canvas.getContext("2d");
          ctx?.drawImage(img, 0, 0);
          iconLogoCache = canvas.toDataURL("image/png");
          resolve(iconLogoCache);
        } catch {
          resolve(null);
        }
      };
      img.onerror = () => resolve(null);
      img.src = logoUrl;
    });
  } catch {
    return null;
  }
};

