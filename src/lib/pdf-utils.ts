// Generate a real scannable QR code as base64 data URL
const generateQrBase64 = async (url: string): Promise<string | null> => {
  try {
    const dataUrl = await QRCode.toDataURL(url, {
      width: 200,
      margin: 1,
      errorCorrectionLevel: "M",
      color: { dark: "#000000", light: "#ffffff" },
    });
    return dataUrl;
  } catch {
    return null;
  }
};

/**
 * Draw a thin 1px border around the entire page
 */
export const addPageBorder = (doc: jsPDF) => {
  const w = doc.internal.pageSize.getWidth();
  const h = doc.internal.pageSize.getHeight();
  doc.setDrawColor(180, 180, 180);
  doc.setLineWidth(0.3);
  doc.rect(BORDER_MARGIN, BORDER_MARGIN, w - BORDER_MARGIN * 2, h - BORDER_MARGIN * 2);
};

/**
 * PDF Header:
 * LEFT: D icon logo + 3 lines text
 * RIGHT: Barcode with doc number
 * Thin line separator below
 */
export const addPdfHeader = async (
  doc: jsPDF,
  docNumber: string,
  options?: { title?: string; verifyUrl?: string }
) => {
  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = CONTENT_MARGIN;
  const headerY = BORDER_MARGIN + 5;

  // Draw page border
  addPageBorder(doc);

  // LEFT: Logo icon
  const logo = await loadIconLogo();
  let textStartX = margin;

  if (logo) {
    try {
      const logoSize = 18;
      doc.addImage(logo, "PNG", margin, headerY - 2, logoSize, logoSize);
      textStartX = margin + logoSize + 4;
    } catch { /* skip */ }
  }

  // LEFT: 3 lines of text next to logo
  doc.setFontSize(8);
  doc.setTextColor(0, 0, 0);
  doc.setFont("helvetica", "normal");
  doc.text(COMPANY.name, textStartX, headerY + 3);

  doc.setFontSize(10);
  doc.setFont("helvetica", "bold");
  doc.text(COMPANY.system, textStartX, headerY + 9);

  doc.setFontSize(8);
  doc.setFont("helvetica", "normal");
  doc.text(COMPANY.office, textStartX, headerY + 14);

  // RIGHT: Barcode with doc number
  const barcodeWidth = 50;
  const barcodeX = pageWidth - margin - barcodeWidth;
  drawBarcode(doc, docNumber, barcodeX, headerY - 1, barcodeWidth, 14);

  // Thin separator line below header
  const lineY = headerY + 19;
  doc.setDrawColor(200, 200, 200);
  doc.setLineWidth(0.3);
  doc.line(margin, lineY, pageWidth - margin, lineY);

  // Document title below separator
  const contentStart = lineY + 5;
  if (options?.title) {
    doc.setFontSize(14);
    doc.setTextColor(13, 27, 42);
    doc.setFont("helvetica", "bold");
    doc.text(String(options.title), pageWidth / 2, contentStart + 5, { align: "center" });
  }

  // Reset
  doc.setTextColor(0, 0, 0);
  doc.setFont("helvetica", "normal");

  return options?.title ? contentStart + 12 : contentStart;
};

