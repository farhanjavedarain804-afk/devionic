/**
 * Custom PDF Header for Applications:
 * LEFT: QR Code (real scannable)
 * CENTER: Devionic Logo + "APPLICATION FOR EMPLOYMENT"
 * RIGHT: Applicant Passport Photo
 */
export const addApplicationHeader = async (
  doc: jsPDF,
  verificationId: string,
  verifyUrl: string,
  title?: string,
  photoUrl?: string
) => {
  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = CONTENT_MARGIN;
  const headerY = BORDER_MARGIN + 5;

  // 1. LEFT: QR Code
  const qrSize = 18;
  try {
    const qrBase64 = await generateQrBase64(verifyUrl);
    if (qrBase64) {
      doc.addImage(qrBase64, "PNG", margin, headerY - 1, qrSize, qrSize);
    }
  } catch { /* skip */ }

  // 2. CENTER: Logo + Title
  const fullLogo = await loadFullLogo();
  if (fullLogo) {
    try {
      const logoW = 42;
      const logoH = 10; 
      doc.addImage(fullLogo, "PNG", (pageWidth / 2) - (logoW / 2), headerY + 1.5, logoW, logoH);
      
      if (title) {
        doc.setFontSize(14);
        doc.setFont("helvetica", "bold");
        doc.setTextColor(13, 27, 42);
        // Added 8.5mm gap between logo bottom and title for professional branding
        doc.text(String(title).toUpperCase(), pageWidth / 2, headerY + 20, { align: "center" });
      }
    } catch { /* skip */ }
  } else if (title) {
    doc.setFontSize(14);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(13, 27, 42);
    doc.text(String(title).toUpperCase(), pageWidth / 2, headerY + 10, { align: "center" });
  }

  // 3. RIGHT: Applicant Photo
  if (photoUrl) {
    try {
      const photoW = 22;
      const photoH = 26;
      doc.setFillColor(248, 248, 248);
      doc.setDrawColor(220, 220, 220);
      doc.rect(pageWidth - margin - photoW, headerY, photoW, photoH, "FD");
      doc.addImage(photoUrl, "JPEG", pageWidth - margin - photoW + 0.5, headerY + 0.5, photoW - 1, photoH - 1);
    } catch { 
      // Fallback
    }
  } else {
    // Empty photo box
    const photoW = 20;
    const photoH = 25;
    doc.setDrawColor(200, 200, 200);
    doc.rect(pageWidth - margin - photoW, headerY, photoW, photoH);
    doc.setFontSize(6);
    doc.setTextColor(150, 150, 150);
    doc.text("PASTE PHOTO", pageWidth - margin - photoW/2, headerY + photoH/2, { align: "center" });
  }

  // Final Header Formatting
  const lineY = headerY + 30;
  doc.setDrawColor(200, 200, 200);
  doc.setLineWidth(0.4);
  doc.line(margin, lineY, pageWidth - margin, lineY);

  return lineY + 6;
};

